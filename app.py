# =========================================================
#        رفع مشکل نمایش برعکس متن فارسی در کنسول ویندوز
# =========================================================
 
def render_fa(text: str) -> str:
    """
    متن فارسی را طوری آماده می‌کند که در کنسول‌های قدیمی ویندوز
    (که خودشان الگوریتم راست‌به‌چپ ندارند) درست و رو به جلو دیده شود.
    اگر کتابخانه نصب نباشد، همان متن اصلی برگردانده می‌شود.
    """
    if not RTL_FIX_AVAILABLE:
        return text
 
    lines = text.split("\n")
    fixed_lines = []
    for line in lines:
        if line.strip() == "":
            fixed_lines.append(line)
            continue
        reshaped = arabic_reshaper.reshape(line)
        fixed_lines.append(get_display(reshaped))
    return "\n".join(fixed_lines)
 
 
def p(text: str = ""):
    """چاپ متن با رفع مشکل جهت نمایش."""
    print(render_fa(text))
 
 

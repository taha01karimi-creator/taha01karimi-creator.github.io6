# کلماتی که به‌تنهایی خیلی عمومی‌اند و نباید باعث تشخیص اشتباه پروژه بشن
PROJECT_MATCH_STOPWORDS = {"برنامه", "لیست", "کارها", "یادداشت", "و", "امن"}
 
 
def _word_match(keyword: str, text: str) -> bool:
    """بررسی می‌کند که keyword به‌صورت یک کلمه/عبارت کامل (نه بخشی از یک کلمه‌ی دیگر) در text وجود دارد."""
    pattern = r"(?<!\w)" + re.escape(keyword) + r"(?!\w)"
    return re.search(pattern, text) is not None
 
 
def match_intent(text: str):
    text = normalize(text)
 
    # اول دنبال جزئیات یک پروژه‌ی خاص می‌گردیم (اولویت بالاتر از greeting و...)
    for project in PROJECTS:
        pname = normalize(project["نام"])
        for word in pname.split():
            word = word.strip("()،")
            if len(word) > 2 and word not in PROJECT_MATCH_STOPWORDS:
                if _word_match(word, text):
                    return ("project_detail", project)
 
    for intent, words in KEYWORDS.items():
        for w in words:
            wn = normalize(w)
            if _word_match(wn, text):
                return intent
 
    return "unknown"
 
 

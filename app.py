def normalize(text: str) -> str:
    """حذف فاصله‌های اضافه، یکسان‌سازی حروف عربی/فارسی مشابه و کوچک کردن حروف لاتین."""
    text = text.strip().lower()
    text = re.sub(r"\s+", " ", text)
    # یکسان‌سازی چند حرف پرکاربرد عربی/فارسی
    text = text.replace("ي", "ی").replace("ك", "ک").replace("‌", " ")
    return text
 
 
